import BitcoinDevKit
import Foundation

let expectedCount = 2048
var words: Set<String> = []
var attempts = 0

while words.count < expectedCount, attempts < 100_000 {
    attempts += 1
    for word in Mnemonic(wordCount: .words24).description.split(separator: " ") {
        words.insert(String(word))
    }
}

guard words.count == expectedCount else {
    FileHandle.standardError.write(
        Data("collected only \(words.count) of \(expectedCount) words\n".utf8)
    )
    exit(1)
}

let sorted = words.sorted()
FileHandle.standardError.write(
    Data("collected \(sorted.count) words in \(attempts) mnemonics\n".utf8)
)

print(
    """
    // Generated by WordlistGenerator. Do not edit.
    // swift run WordlistGenerator > Sources/WalletCore/BIP39Wordlist.swift

    public enum BIP39Wordlist {
        public static let words: [String] = raw.split(separator: " ").map(String.init)

        public static let wordSet: Set<String> = Set(words)

        public static func contains(_ word: String) -> Bool {
            wordSet.contains(word.lowercased())
        }

        public static func suggestions(for prefix: String, limit: Int = 3) -> [String] {
            let needle = prefix.lowercased()
            guard !needle.isEmpty else { return [] }
            return words.lazy.filter { $0.hasPrefix(needle) }.prefix(limit).map { $0 }
        }

        private static let raw =
            "\(sorted.joined(separator: " "))"
    }
    """
)
